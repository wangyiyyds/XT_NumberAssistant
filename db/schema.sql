-- PostgreSQL schema converted from the MySQL 8.0 dump (video_assistant).
-- MySQL-specific syntax (ENGINE, CHARSET, AUTO_INCREMENT, USING BTREE,
-- ON UPDATE CURRENT_TIMESTAMP) has been replaced with PostgreSQL equivalents.
--
-- Usage:
--   psql -U xianting -d xianting_chat -f db/schema.sql
--   psql -U xianting -d xianting_chat -f db/data.sql

BEGIN;

DROP TABLE IF EXISTS
    t_prompt,
    t_agent,
    t_balance,
    t_conversation,
    t_department,
    t_inspiration_keyword,
    t_inspiration_video,
    t_message,
    t_user
CASCADE;

CREATE TABLE t_user (
    id               bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
    public_id        varchar(64)  NOT NULL UNIQUE,
    brand            varchar(32)  NOT NULL DEFAULT 'xianting',
    email            varchar(128) NOT NULL UNIQUE,
    password         varchar(256) NOT NULL,
    name             varchar(64),
    avatar           varchar(256),
    email_verified   boolean      NOT NULL DEFAULT false,
    disabled         boolean      NOT NULL DEFAULT false,
    contract_read_at timestamp,
    created_at       timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE t_balance (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
    user_id             bigint  NOT NULL UNIQUE,
    token_credits       bigint  NOT NULL DEFAULT 0,
    auto_refill_enabled boolean NOT NULL DEFAULT false,
    expire_at           timestamp
);

CREATE TABLE t_department (
    id         bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 8) PRIMARY KEY,
    public_id  varchar(64) NOT NULL UNIQUE,
    name       varchar(64) NOT NULL,
    enabled    boolean     NOT NULL DEFAULT true,
    brand_only boolean     NOT NULL DEFAULT false,
    sort_order integer     NOT NULL DEFAULT 0
);

CREATE TABLE t_agent (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 23) PRIMARY KEY,
    public_id             varchar(64)   NOT NULL UNIQUE,
    department_id         bigint,
    name                  varchar(128)  NOT NULL,
    description           varchar(1024),
    avatar                varchar(512),
    category              varchar(64),
    is_preset             boolean       NOT NULL DEFAULT true,
    conversation_starters varchar(2048),
    instructions          text,
    created_at            timestamp     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE t_conversation (
    id         bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 3) PRIMARY KEY,
    public_id  varchar(64) NOT NULL UNIQUE,
    user_id    bigint      NOT NULL,
    agent_id   bigint      NOT NULL,
    title      varchar(256),
    endpoint   varchar(64) NOT NULL DEFAULT 'agents',
    created_at timestamp   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_conversation_user ON t_conversation (user_id, agent_id);

CREATE TABLE t_message (
    id                bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 5) PRIMARY KEY,
    public_id         varchar(64) NOT NULL UNIQUE,
    conversation_id   bigint      NOT NULL,
    parent_message_id varchar(64),
    sender            varchar(16) NOT NULL,
    text              text,
    error             boolean     NOT NULL DEFAULT false,
    created_at        timestamp   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_message_conversation ON t_message (conversation_id);

CREATE TABLE t_inspiration_keyword (
    id               bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
    user_id          bigint       NOT NULL,
    keyword          varchar(128) NOT NULL,
    sort_order       integer      NOT NULL DEFAULT 0,
    cache_expires_at timestamp,
    created_at       timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE t_inspiration_video (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 11) PRIMARY KEY,
    keyword_id          bigint       NOT NULL,
    author              varchar(128),
    fans                varchar(32),
    duration            varchar(16),
    publish_date        varchar(16),
    title               varchar(1024),
    likes               varchar(32),
    cover_url           varchar(512),
    video_url           varchar(512),
    low_fans_high_likes boolean      NOT NULL DEFAULT false,
    created_at          timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_video_keyword ON t_inspiration_video (keyword_id);

-- Prompt version management. Not used by the current Java API, kept because
-- the source database contains it.
-- MySQL VIRTUAL generated columns have no PostgreSQL equivalent; PostgreSQL
-- only supports STORED generated columns, which behave the same for reads.
CREATE TABLE t_prompt (
    id               bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1030) PRIMARY KEY,
    public_id        varchar(64)  NOT NULL,
    agent_id         bigint       NOT NULL,
    version          integer      NOT NULL,
    version_tag      varchar(32),
    name             varchar(128),
    description      varchar(1024),
    prompt_type      varchar(32)  NOT NULL DEFAULT 'SYSTEM',
    content          text         NOT NULL,
    variables        jsonb,
    model_config     jsonb,
    status           varchar(16)  NOT NULL DEFAULT 'DRAFT',
    parent_prompt_id bigint,
    created_by       varchar(64),
    updated_by       varchar(64),
    created_at       timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at     timestamp,
    archived_at      timestamp,
    active_agent_id  bigint GENERATED ALWAYS AS (
        CASE WHEN status = 'ACTIVE' THEN agent_id ELSE NULL END
    ) STORED,
    CONSTRAINT uk_public_id UNIQUE (public_id),
    CONSTRAINT uk_agent_version UNIQUE (agent_id, version),
    -- Multiple NULLs do not conflict in PostgreSQL, so this keeps at most one
    -- ACTIVE prompt per agent, same as the MySQL unique index.
    CONSTRAINT uk_agent_active UNIQUE (active_agent_id),
    CONSTRAINT fk_prompt_agent FOREIGN KEY (agent_id) REFERENCES t_agent (id)
        ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT fk_prompt_parent FOREIGN KEY (parent_prompt_id) REFERENCES t_prompt (id)
        ON DELETE SET NULL ON UPDATE RESTRICT
);

CREATE INDEX idx_agent_status ON t_prompt (agent_id, status);
CREATE INDEX idx_agent_created ON t_prompt (agent_id, created_at);
CREATE INDEX idx_parent ON t_prompt (parent_prompt_id);

-- MySQL's ON UPDATE CURRENT_TIMESTAMP has no column-level equivalent.
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER t_prompt_set_updated_at
BEFORE UPDATE ON t_prompt
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMIT;